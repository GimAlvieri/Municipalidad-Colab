-- Demo educativa de RR. HH. No cargar datos personales reales.
-- PostgreSQL (por ejemplo, proyecto Supabase).

begin;

create schema if not exists rrhh_demo;

create table if not exists rrhh_demo.areas (
    id smallint generated by default as identity primary key,
    nombre text not null unique
);

create table if not exists rrhh_demo.solicitudes (
    id bigint generated by default as identity primary key,
    codigo_trabajador text not null,
    area_id smallint not null references rrhh_demo.areas(id),
    tipo text not null check (tipo in ('vacaciones', 'permiso')),
    fecha_inicio date not null,
    fecha_fin date not null,
    estado text not null default 'pendiente'
        check (estado in ('pendiente', 'aprobada', 'rechazada')),
    observacion_demo text,
    creado_en timestamptz not null default now(),
    check (fecha_fin >= fecha_inicio)
);

create index if not exists solicitudes_estado_idx
    on rrhh_demo.solicitudes (estado);
create index if not exists solicitudes_fechas_idx
    on rrhh_demo.solicitudes (fecha_inicio, fecha_fin);

insert into rrhh_demo.areas (nombre) values
    ('Administración'), ('Obras'), ('Servicios Municipales')
on conflict (nombre) do nothing;

insert into rrhh_demo.solicitudes
    (codigo_trabajador, area_id, tipo, fecha_inicio, fecha_fin, estado, observacion_demo)
select v.codigo, a.id, v.tipo, v.inicio::date, v.fin::date, v.estado, v.observacion
from (values
    ('DEMO-001', 'Administración', 'vacaciones', '2026-12-01', '2026-12-05', 'pendiente', 'Registro ficticio'),
    ('DEMO-002', 'Obras', 'permiso', '2026-11-20', '2026-11-20', 'aprobada', 'Registro ficticio'),
    ('DEMO-003', 'Servicios Municipales', 'vacaciones', '2026-12-14', '2026-12-18', 'rechazada', 'Registro ficticio')
) as v(codigo, area, tipo, inicio, fin, estado, observacion)
join rrhh_demo.areas a on a.nombre = v.area
where not exists (
    select 1 from rrhh_demo.solicitudes s
    where s.codigo_trabajador = v.codigo
      and s.fecha_inicio = v.inicio::date
      and s.tipo = v.tipo
);

create or replace view rrhh_demo.resumen_por_estado as
select a.nombre as area, s.estado, s.tipo, count(*) as cantidad
from rrhh_demo.solicitudes s
join rrhh_demo.areas a on a.id = s.area_id
group by a.nombre, s.estado, s.tipo;

commit;

